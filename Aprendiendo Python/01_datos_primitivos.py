###
# Los tipos de datos primitivos :
# Son los datos más básicos que el leguaje entiende de forma nativa. Bloques de construcción que no se puede 
# descomponer.

###
# Enteros (int) positivo o negativo. 
print(type(3))
print(type(-2))

# Con decimales (float).
print(type(3.4))

# Cadema de texto (str).
print(type("Hola python"))

# Boleano (bool), si es True o False.
print(type(True))

# Complejos (complex).
print(type(1 + 2j))

# Bytes (bytes).
print(type(b"Hola"))

# Nulo (NoneType)
print(type(None))