### Datos compuestos ###
# En python, los datos compuestos son estructuras que pueden almacenar valor.

# Listas (list)
fruits = ["naranjas","manzanas","peras"]
print(type(fruits))

# Tuplas (tuple)
num = (1,2,3,4,5)
print(type(num))

# Conjunto (sets)
num = {1,2,3,4,5,6}
print(type(num))

# Diccionario (Dicctionaries)
dict = {"Nombre":"Carquialo", "Edad":32}
print(type(dict))